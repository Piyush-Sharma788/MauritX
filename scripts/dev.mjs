#!/usr/bin/env node
/**
 * `npm run dev`: starts the whole MarutiX development environment with one command.
 *
 *   mongo     local MongoDB (only if MONGODB_URI points at this machine and nothing is listening)
 *   web       Next.js app, API routes and the WhatsApp Cloud API webhook
 *   jobs      background jobs: coordination waves, discovery, outreach, retention,
 *             and (MESSAGING_PROVIDER=whatsapp_cloud) the WhatsApp outbox
 *   whatsapp  WhatsApp Web pilot worker (MESSAGING_PROVIDER=whatsapp_web): bot, outbox, delivery acks
 *
 * Ctrl+C stops everything, including a MongoDB this script started.
 * No dependencies beyond Node itself.
 *
 * Runtime data (MongoDB files, the WhatsApp browser profile) lives in MARUTIX_DATA_DIR
 * (default ~/.marutix), never inside the project: `next dev` watches the project folder
 * and treats every write there as a code change, which rebuilds and reloads open pages
 * in a loop.
 */
import { spawn, spawnSync } from "node:child_process";
import { randomBytes } from "node:crypto";
import { existsSync, mkdirSync, readFileSync, renameSync, writeFileSync, chmodSync } from "node:fs";
import { createConnection } from "node:net";
import { homedir } from "node:os";
import { dirname, join, relative, resolve, sep } from "node:path";
import { fileURLToPath } from "node:url";
import { parseEnv } from "node:util";

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const ENV_FILE = join(ROOT, ".env.local");
const BIN = join(ROOT, "node_modules", ".bin");
const sleep = (ms) => new Promise((r) => setTimeout(r, ms));
const expandHome = (p) => (p === "~" ? homedir() : p.startsWith("~/") ? join(homedir(), p.slice(2)) : p);
let DATA_DIR = resolve(ROOT, expandHome(process.env.MARUTIX_DATA_DIR || "~/.marutix")); // final value read with .env.local in main()
const insideProject = (p) => p === ROOT || p.startsWith(ROOT + sep);

// ---------------------------------------------------------------- output
const tty = process.stdout.isTTY && !process.env.NO_COLOR;
const paint = (code) => (s) => (tty ? `\x1b[${code}m${s}\x1b[0m` : s);
const c = { dim: paint("2"), bold: paint("1"), red: paint("31"), green: paint("32"), yellow: paint("33"), blue: paint("34"), magenta: paint("35"), cyan: paint("36") };
const LABEL_COLOR = { dev: c.bold, mongo: c.green, web: c.cyan, jobs: c.magenta, whatsapp: c.blue };
const label = (name) => (LABEL_COLOR[name] ?? c.bold)(`[${name}]`.padEnd(11));
const log = (name, line) => process.stdout.write(`${label(name)}${line}\n`);
const info = (line) => log("dev", line);
const fail = (lines) => {
  for (const line of [].concat(lines)) process.stderr.write(`${label("dev")}${c.red(line)}\n`);
};

// ---------------------------------------------------------------- environment
/** First run: create .env.local from .env.example with freshly generated secrets. */
function ensureEnvFile() {
  if (existsSync(ENV_FILE)) return false;
  const example = readFileSync(join(ROOT, ".env.example"), "utf8");
  const b64 = () => randomBytes(32).toString("base64");
  const generated = {
    AUTH_JWT_SECRET: b64(),
    OTP_HASH_SECRET: b64(),
    PII_ENCRYPTION_KEY: b64(),
    WHATSAPP_WEB_WORKER_SECRET: b64(),
    OTP_PROVIDER: "development",
  };
  const body = example
    .split("\n")
    .map((line) => {
      const m = /^([A-Z0-9_]+)=\s*$/.exec(line);
      return m && generated[m[1]] ? `${m[1]}=${generated[m[1]]}` : line;
    })
    .join("\n");
  writeFileSync(ENV_FILE, body.replace(/^# MarutiX environment\..*$/m, "# MarutiX local development environment (generated by npm run dev). Contains real secrets: never commit it."), { mode: 0o600 });
  chmodSync(ENV_FILE, 0o600);
  return true;
}

/** .env.local with real environment variables taking precedence (the same rule Next.js and Node apply). */
function loadEnv() {
  const fromFile = parseEnv(readFileSync(ENV_FILE, "utf8"));
  const merged = { ...fromFile };
  for (const [k, v] of Object.entries(process.env)) if (v !== undefined) merged[k] = v;
  const get = (k, fallback = "") => {
    const v = merged[k];
    return v === undefined || v.trim() === "" ? fallback : v.trim();
  };
  return { get };
}

// ---------------------------------------------------------------- ports and MongoDB
function portOpen(host, port, timeoutMs = 700) {
  return new Promise((done) => {
    const socket = createConnection({ host, port });
    const finish = (open) => {
      socket.destroy();
      done(open);
    };
    socket.setTimeout(timeoutMs, () => finish(false));
    socket.once("connect", () => finish(true));
    socket.once("error", () => finish(false));
  });
}

function whoListens(port) {
  const r = spawnSync("lsof", ["-nP", `-iTCP:${port}`, "-sTCP:LISTEN"], { encoding: "utf8" });
  const line = (r.stdout ?? "").split("\n")[1];
  if (!line) return "another process";
  const [command, pid] = line.trim().split(/\s+/);
  return `${command} (pid ${pid})`;
}

const LOCAL_HOSTS = new Set(["127.0.0.1", "localhost", "::1", "[::1]", "0.0.0.0"]);

/** host/port of a single-host, non-SRV MongoDB URI on this machine; null for Atlas/remote URIs. */
function localMongoTarget(uri) {
  const m = /^mongodb:\/\/(?:[^@/]*@)?([^/?,]+)(?:\/|$|\?)/.exec(uri);
  if (!m) return null;
  const hostPort = m[1];
  const ipv6 = /^\[([^\]]+)\](?::(\d+))?$/.exec(hostPort);
  const host = ipv6 ? ipv6[1] : hostPort.split(":")[0];
  const port = Number(ipv6 ? ipv6[2] ?? 27017 : hostPort.split(":")[1] ?? 27017);
  return LOCAL_HOSTS.has(host) ? { host: host === "localhost" || host === "0.0.0.0" ? "127.0.0.1" : host, port } : null;
}

function hasCommand(cmd) {
  return spawnSync("sh", ["-c", `command -v ${cmd}`], { stdio: "ignore" }).status === 0;
}

// ---------------------------------------------------------------- process supervision
const children = new Map(); // name -> { child, spec }
const ready = new Set(); // names whose log printed their readiness line
let shuttingDown = false;

function pipeLines(name, stream, write) {
  let buffer = "";
  stream.setEncoding("utf8");
  stream.on("data", (chunk) => {
    buffer += chunk;
    let i;
    while ((i = buffer.indexOf("\n")) >= 0) {
      write(`${label(name)}${buffer.slice(0, i)}\n`);
      buffer = buffer.slice(i + 1);
    }
  });
  stream.on("end", () => buffer && write(`${label(name)}${buffer}\n`));
}

/**
 * Starts a process and restarts it if it crashes. A process that keeps dying within
 * seconds of starting is misconfigured: it's left stopped with a clear message, and
 * if it's essential the whole environment stops.
 */
function supervise(spec, attempt = 0) {
  const startedAt = Date.now();
  const child = spawn(spec.cmd, spec.args, {
    cwd: ROOT,
    env: { ...process.env, ...spec.env, FORCE_COLOR: tty ? "1" : "0" },
    stdio: ["ignore", "pipe", "pipe"],
    detached: process.platform !== "win32", // own process group, so a stop reaches its whole tree (e.g. Chromium)
  });
  children.set(spec.name, { child, spec });
  const watch = (write) => (s) => {
    if (spec.readyWhen?.test(s)) ready.add(spec.name);
    write(s);
  };
  pipeLines(spec.name, child.stdout, watch((s) => process.stdout.write(s)));
  pipeLines(spec.name, child.stderr, watch((s) => process.stderr.write(s)));

  child.on("error", (error) => fail(`${spec.name}: could not start ${spec.cmd}: ${error.message}`));
  child.on("exit", (code, signal) => {
    if (children.get(spec.name)?.child === child) children.delete(spec.name);
    ready.delete(spec.name);
    if (shuttingDown) return;
    const quick = Date.now() - startedAt < 15_000;
    const next = quick ? attempt + 1 : 0;
    const why = signal ? `signal ${signal}` : `exit code ${code}`;
    if (spec.essential && next > 3) {
      fail([`${spec.name} keeps failing at startup (${why}). Stopping the environment; see the [${spec.name}] lines above.`]);
      void shutdown(1);
      return;
    }
    if (next > 3) {
      fail([
        `${spec.name} keeps failing at startup (${why}) and has been left stopped. The rest of MarutiX is still running.`,
        `Fix the problem shown in the [${spec.name}] lines above, then restart npm run dev.`,
      ]);
      return;
    }
    const delay = Math.min(30_000, 1_000 * 2 ** Math.max(0, next - 1));
    info(c.yellow(`${spec.name} stopped (${why}); restarting in ${Math.round(delay / 1000)}s`));
    setTimeout(() => !shuttingDown && supervise(spec, next), delay);
  });
  return child;
}

function signalChild(child, signal) {
  try {
    child.kill(signal);
  } catch {
    /* already gone */
  }
}

function signalTree(child, signal) {
  try {
    if (process.platform !== "win32") process.kill(-child.pid, signal);
    else child.kill(signal);
  } catch {
    /* already gone */
  }
}

async function shutdown(code = 0) {
  if (shuttingDown) return;
  shuttingDown = true;
  info(c.dim("stopping…"));
  // Apps first, MongoDB last, so the workers can release their leases and write their final state.
  const order = [...children.values()].sort((a, b) => Number(a.spec.name === "mongo") - Number(b.spec.name === "mongo"));
  for (const group of [order.filter((e) => e.spec.name !== "mongo"), order.filter((e) => e.spec.name === "mongo")]) {
    const exits = group.map(({ child }) => new Promise((r) => (child.exitCode !== null || child.signalCode !== null ? r() : child.once("exit", r))));
    // Ask each service itself to stop, never its whole process group: the WhatsApp worker
    // must close Chromium on its own. Killing Chromium alongside it is an unclean exit, after
    // which Chromium restores stale WhatsApp tabs that fight over the session on next start.
    for (const { child } of group) signalChild(child, "SIGTERM");
    // Only if something hangs, force-stop the whole tree (the worker allows 15 s to close WhatsApp).
    const killer = setTimeout(() => group.forEach(({ child }) => signalTree(child, "SIGKILL")), 25_000);
    await Promise.all(exits);
    clearTimeout(killer);
  }
  process.exit(code);
}
process.on("SIGINT", () => void shutdown(0));
process.on("SIGTERM", () => void shutdown(0));
process.on("SIGHUP", () => void shutdown(0));

// ---------------------------------------------------------------- runtime data outside the project
const tilde = (p) => (p.startsWith(homedir() + sep) ? `~/${relative(homedir(), p)}` : p);

/**
 * Earlier versions kept runtime data in ./.data, where every write made `next dev`
 * rebuild and reload open pages. Move it out once, keeping the database and the
 * linked WhatsApp session; then warn about anything still configured inside.
 */
function relocateRuntimeData(env) {
  mkdirSync(DATA_DIR, { recursive: true, mode: 0o700 });
  const moves = [
    [join(ROOT, ".data", "mongodb"), join(DATA_DIR, "mongodb")],
    [join(ROOT, ".data", "mongod.log"), join(DATA_DIR, "mongod.log")],
    [join(ROOT, ".data", "whatsapp-web-cache"), join(DATA_DIR, "whatsapp-web-cache")],
  ];
  const sessionDir = resolve(ROOT, expandHome(env.get("WHATSAPP_WEB_SESSION_DIR", "~/.marutix/whatsapp-session")));
  if (!insideProject(sessionDir)) moves.push([join(ROOT, ".data", "whatsapp-session"), sessionDir]);
  for (const [from, to] of moves) {
    if (!existsSync(from) || existsSync(to)) continue;
    try {
      mkdirSync(dirname(to), { recursive: true, mode: 0o700 });
      renameSync(from, to);
      info(`moved ${relative(ROOT, from)} → ${tilde(to)} (runtime data no longer lives in the project folder)`);
    } catch (error) {
      fail(`Couldn't move ${relative(ROOT, from)} to ${tilde(to)}: ${error.message}. Move it by hand while MarutiX is stopped.`);
    }
  }
  if (insideProject(sessionDir)) {
    info(c.yellow(`WHATSAPP_WEB_SESSION_DIR (${relative(ROOT, sessionDir)}) is inside the project folder. Chromium writes there constantly,`));
    info(c.yellow("so open pages will keep rebuilding and reloading. Set WHATSAPP_WEB_SESSION_DIR=~/.marutix/whatsapp-session in .env.local."));
  }
}

// ---------------------------------------------------------------- main
async function main() {
  const major = Number(process.versions.node.split(".")[0]);
  if (major < 20) {
    fail(`Node.js 20.6 or newer is required (found ${process.versions.node}).`);
    process.exit(1);
  }
  if (!existsSync(join(BIN, "next")) || !existsSync(join(BIN, "tsx"))) {
    fail("Dependencies are not installed. Run: npm install");
    process.exit(1);
  }
  if (ensureEnvFile()) info(c.yellow("Created .env.local from .env.example with newly generated secrets (development sign-in codes, no WhatsApp credentials)."));
  const env = loadEnv();
  DATA_DIR = resolve(ROOT, expandHome(env.get("MARUTIX_DATA_DIR", "~/.marutix")));
  relocateRuntimeData(env);

  // --- web port: must match APP_BASE_URL exactly, or CSRF origin checks reject every form.
  let baseUrl;
  try {
    baseUrl = new URL(env.get("APP_BASE_URL", "http://localhost:3000"));
  } catch {
    fail("APP_BASE_URL in .env.local is not a valid URL (expected e.g. http://localhost:3000).");
    process.exit(1);
  }
  const webPort = Number(process.env.PORT || baseUrl.port || (baseUrl.protocol === "https:" ? 443 : 80));
  if (process.env.PORT && baseUrl.port && process.env.PORT !== baseUrl.port) {
    fail(`PORT=${process.env.PORT} doesn't match APP_BASE_URL (${baseUrl.origin}). Set both to the same port.`);
    process.exit(1);
  }

  const provider = env.get("MESSAGING_PROVIDER", "whatsapp_web");
  if (!["whatsapp_web", "whatsapp_cloud"].includes(provider)) {
    fail(`MESSAGING_PROVIDER must be whatsapp_web or whatsapp_cloud (found "${provider}").`);
    process.exit(1);
  }
  const runPilot = provider === "whatsapp_web";
  let workerPort = null;
  if (runPilot) {
    try {
      workerPort = Number(new URL(env.get("WHATSAPP_WEB_WORKER_URL", "http://127.0.0.1:3100")).port || 80);
    } catch {
      fail("WHATSAPP_WEB_WORKER_URL is not a valid URL (expected http://127.0.0.1:3100).");
      process.exit(1);
    }
  }

  // --- ports must be free: say who holds them instead of silently moving.
  const busy = [];
  if (await portOpen("127.0.0.1", webPort)) busy.push(`Port ${webPort} (web, from APP_BASE_URL) is in use by ${whoListens(webPort)}.`);
  if (workerPort && (await portOpen("127.0.0.1", workerPort))) busy.push(`Port ${workerPort} (WhatsApp worker control, from WHATSAPP_WEB_WORKER_URL) is in use by ${whoListens(workerPort)}.`);
  if (busy.length) {
    fail([...busy, "Is MarutiX already running in another terminal? Stop it, or free the port(s) and try again."]);
    process.exit(1);
  }

  // --- MongoDB
  const mongoUri = env.get("MONGODB_URI");
  if (!mongoUri) {
    fail("MONGODB_URI is not set in .env.local.");
    process.exit(1);
  }
  const local = localMongoTarget(mongoUri);
  if (local && !(await portOpen(local.host, local.port))) {
    if (!hasCommand("mongod")) {
      fail([
        `MongoDB isn't running on ${local.host}:${local.port} and the mongod command isn't installed.`,
        "Install it (macOS: brew tap mongodb/brew && brew install mongodb-community) or point MONGODB_URI at MongoDB Atlas.",
      ]);
      process.exit(1);
    }
    const dbPath = join(DATA_DIR, "mongodb");
    mkdirSync(dbPath, { recursive: true, mode: 0o700 });
    // mongod logs JSON for every index build and connection; keep it in a file, not the terminal.
    const logPath = join(DATA_DIR, "mongod.log");
    info(`starting MongoDB on ${local.host}:${local.port} (data in ${tilde(dbPath)}, log in ${tilde(logPath)})`);
    supervise({ name: "mongo", cmd: "mongod", args: ["--dbpath", dbPath, "--bind_ip", local.host, "--port", String(local.port), "--quiet", "--logpath", logPath, "--logappend"], essential: true });
    const deadline = Date.now() + 30_000;
    while (!(await portOpen(local.host, local.port))) {
      if (shuttingDown) return;
      if (Date.now() > deadline) {
        fail("MongoDB didn't start within 30 seconds; see the [mongo] lines above.");
        return shutdown(1);
      }
      await sleep(300);
    }
    info("MongoDB is ready");
  } else if (local) {
    info(`using the MongoDB already running on ${local.host}:${local.port}`);
  } else {
    info("using the remote MongoDB from MONGODB_URI");
  }

  // --- application processes
  const tsx = join(BIN, "tsx");
  const tsxArgs = (entry) => ["--conditions=react-server", `--env-file=${ENV_FILE}`, entry];
  supervise({ name: "web", cmd: join(BIN, "next"), args: ["dev", "--port", String(webPort)], essential: true });
  // IPv4 first for the jobs worker: on some networks IPv6 routes to the public OpenStreetMap
  // servers hang until the timeout. Set MARUTIX_JOBS_IPV6=true to keep Node's default order.
  const jobsEnv = env.get("MARUTIX_JOBS_IPV6") === "true" ? {} : { NODE_OPTIONS: [process.env.NODE_OPTIONS, "--dns-result-order=ipv4first"].filter(Boolean).join(" ") };
  supervise({ name: "jobs", cmd: tsx, args: tsxArgs("src/worker/jobs/main.ts"), env: jobsEnv, readyWhen: /"event":"jobs\.worker\.started"/ });
  if (runPilot) supervise({ name: "whatsapp", cmd: tsx, args: tsxArgs("src/worker/whatsapp/main.ts"), readyWhen: /"event":"whatsapp\.control_listening"/ });

  // --- readiness
  const health = `http://127.0.0.1:${webPort}/api/health`;
  const deadline = Date.now() + 180_000;
  let healthy = false;
  while (!shuttingDown && Date.now() < deadline) {
    try {
      const res = await fetch(health, { signal: AbortSignal.timeout(60_000) });
      if (res.ok) {
        healthy = true;
        break;
      }
    } catch {
      /* compiling or not listening yet */
    }
    await sleep(1_000);
  }
  // The workers report readiness in their own logs; give them a little longer than the web app.
  const workers = runPilot ? ["jobs", "whatsapp"] : ["jobs"];
  const workersBy = Date.now() + 60_000;
  while (!shuttingDown && Date.now() < workersBy && !workers.every((w) => ready.has(w))) await sleep(250);
  if (shuttingDown) return;
  if (!healthy) fail(`The web app didn't report healthy at ${health} within 3 minutes; see the [web] lines above.`);
  printSummary(env, { baseUrl, provider, runPilot, healthy });
}

function printSummary(env, { baseUrl, provider, runPilot, healthy }) {
  const set = (k) => env.get(k) !== "";
  const blockers = [];
  const ok = (s) => `${c.green("✓")} ${s}`;
  const warn = (s) => `${c.yellow("!")} ${s}`;
  const bad = (s) => `${c.red("✗")} ${s}`;
  const state = (name, text) => (ready.has(name) ? ok(text) : bad(`${text}  ${c.red("— NOT running, see the [" + name + "] lines above")}`));
  const lines = [
    healthy ? ok(`web          ${baseUrl.origin}  (healthy, database up)`) : bad(`web          ${baseUrl.origin}  (NOT healthy)`),
    state("jobs", "jobs worker  coordination waves, discovery, outreach, retention" + (provider === "whatsapp_cloud" ? ", WhatsApp outbox" : "")),
  ];

  if (runPilot) {
    lines.push(state("whatsapp", "whatsapp     WhatsApp Web pilot worker (bot, outbox, delivery receipts)"));
    lines.push(warn(`             link a phone: sign in as an admin, open ${baseUrl.origin}/admin/whatsapp, press Connect and scan the QR`));
    if (!set("WHATSAPP_WEB_PUBLIC_NUMBER")) blockers.push("WHATSAPP_WEB_PUBLIC_NUMBER is empty: the website's \"Become a donor\" button has no WhatsApp number to open.");
  } else {
    const missing = ["WHATSAPP_ACCESS_TOKEN", "WHATSAPP_PHONE_NUMBER_ID", "WHATSAPP_APP_SECRET", "WHATSAPP_WEBHOOK_VERIFY_TOKEN"].filter((k) => !set(k));
    lines.push(ok(`whatsapp     official Cloud API; webhook ${baseUrl.origin}/api/v1/webhooks/whatsapp`));
    if (missing.length) blockers.push(`Cloud API credentials missing: ${missing.join(", ")}.`);
    if (!set("WHATSAPP_TEMPLATE_EMERGENCY_ALERT")) blockers.push("WHATSAPP_TEMPLATE_EMERGENCY_ALERT is empty: donors who haven't messaged in 24 h can't be alerted.");
    if (baseUrl.protocol !== "https:") lines.push(warn("             Meta needs a public https webhook URL; use a tunnel (see docs/WHATSAPP_BOT_GUIDE.md)"));
  }

  const otp = env.get("OTP_PROVIDER") || (set("WHATSAPP_ACCESS_TOKEN") && set("WHATSAPP_PHONE_NUMBER_ID") && set("WHATSAPP_OTP_TEMPLATE_NAME") ? "whatsapp" : "development");
  if (otp === "development") lines.push(warn("sign-in codes are printed in the [web] log (OTP_PROVIDER=development), not sent"));
  else if (otp === "whatsapp_web") lines.push(ok("sign-in codes sent from the linked WhatsApp phone (development only); printed in the [web] log until a phone is linked"));
  else lines.push(ok("sign-in codes sent by WhatsApp (authentication template)"));

  if (env.get("AI_PROVIDER", "none") === "anthropic") lines.push(ok(`AI           Claude (${env.get("AI_MODEL", "claude-opus-5-5")}) interprets free text`));
  else lines.push(warn("AI           off (AI_PROVIDER=none): the bot uses commands and keyword matching"));
  if (env.get("EMAIL_PROVIDER", "none") === "none") lines.push(warn("email        off (EMAIL_PROVIDER=none): institution outreach email is not sent"));
  if (env.get("DISCOVERY_PROVIDER", "none") === "none") lines.push(warn("discovery    off (DISCOVERY_PROVIDER=none): only institutions already in MarutiX are contacted"));
  else lines.push(ok(`discovery    ${env.get("DISCOVERY_PROVIDER")}: hospitals and blood banks found and refreshed automatically`));
  if (env.get("EMAIL_PROVIDER", "none") !== "none") lines.push(ok(`email        ${env.get("EMAIL_PROVIDER")} via ${env.get("SMTP_HOST", "?")}: institution outreach email`));

  const allUp = healthy && ready.has("jobs") && (!runPilot || ready.has("whatsapp"));
  const out = ["", c.bold(allUp ? "MarutiX is running." : "MarutiX started with problems (see ✗ below)."), ...lines.map((l) => `  ${l}`)];
  if (blockers.length) out.push("", c.yellow("Needs external setup before real WhatsApp messages flow:"), ...blockers.map((b) => `  - ${b}`));
  out.push("", c.dim("Guide: docs/WHATSAPP_BOT_GUIDE.md   Stop: Ctrl+C"), "");
  for (const l of out) info(l);
}

main().catch((error) => {
  fail(error instanceof Error ? error.stack ?? error.message : String(error));
  void shutdown(1);
});
